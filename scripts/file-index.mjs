// Builds docs/FILE-INDEX.md from the "FILE GUIDE" comment at the top of every file.
// Run: node scripts/file-index.mjs   (re-run after changing a header)
import { readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";

const files = execSync("git ls-files --cached --others --exclude-standard").toString().trim().split("\n")
  .filter((f) => /\.(ts|tsx|mjs|mts|css|yml)$/.test(f) && f !== "next-env.d.ts");

const SECTIONS = [
  ["app/", "app/: the screens", "One folder per web address. page.tsx is what you see; actions.ts runs on the server when you press a button."],
  ["components/", "components/: shared pieces", "Used by many screens."],
  ["lib/", "lib/: the brains", "No screens. Talks to Flagsmith and the database, and holds the business rules."],
  ["scripts/", "scripts/: run by hand", "npm commands for demo data, Flagsmith setup and simulated traffic."],
  ["", "Project root: settings", "Config files at the top of the project."],
];

const guide = (src) => {
  const lines = src.split(/\r?\n/);
  const start = lines.findIndex((l) => l.includes("FILE GUIDE"));
  if (start < 0 || start > 3) return null;
  const hash = lines[start].trimStart().startsWith("#");
  const body = [];
  for (const l of lines.slice(start + 1)) {
    if (hash ? !l.startsWith("#") : l.includes("*/")) break;
    body.push(l.replace(/^\s*(\*|#)\s?/, "").trim());
  }
  return body.filter(Boolean).join(" ");
};

let out = "# File index\n\nEvery file's `FILE GUIDE` note in one place, grouped by folder. This page is generated by `node scripts/file-index.mjs` from the comment at the top of each file, so the two always match.\n\nFor the folder map and flow diagrams, see [FOLDER-GUIDE.md](FOLDER-GUIDE.md). For the behind-the-scenes tour, see [HOW-IT-WORKS.md](HOW-IT-WORKS.md).\n";
const used = new Set();
for (const [prefix, title, blurb] of SECTIONS) {
  const group = files.filter((f) => !used.has(f) && (prefix ? f.startsWith(prefix) : !f.includes("/"))).sort();
  if (!group.length) continue;
  out += `\n## ${title}\n\n${blurb}\n\n| File | What it does and what it connects to |\n|---|---|\n`;
  for (const f of group) {
    used.add(f);
    const g = guide(readFileSync(f, "utf8")) ?? "(no file guide yet)";
    out += `| [${f}](../${f.replace(/\[/g, "%5B").replace(/\]/g, "%5D")}) | ${g.replace(/\|/g, "\|")} |\n`;
  }
}
out += "\n## Not code, no header\n\n| File | What it is |\n|---|---|\n| `package.json` | Libraries the app uses, and the `npm run …` commands |\n| `package-lock.json` | Exact library versions (generated) |\n| `tsconfig.json` | TypeScript settings |\n| `.env.example` | The list of secret keys, values blank |\n| `.env.local` | Your real keys. Not in git |\n| `docs/*.md` | The PRD, these guides, the demo script |\n| `public/` | Favicon and starter images |\n| `uploads/` | Seller banner images. Not in git |\n";
writeFileSync("docs/FILE-INDEX.md", out);
console.log(`docs/FILE-INDEX.md: ${used.size} files`);
